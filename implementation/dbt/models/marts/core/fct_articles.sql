-- Dashboard-ready article feed: one row per article, with story context. Full article text is intentionally
-- excluded (only has_content), keeping the table light for FastAPI/Next.js.
select
    e.article_key,
    e.article_id,
    e.article_title,
    e.original_url,
    e.canonical_url_hash,
    e.link_availability,
    e.has_content,
    e.has_description,
    e.has_image,
    e.story_key,
    e.story_id,
    e.story_title,
    s.story_membership_status,
    s.article_count as story_article_count,
    s.source_count as story_source_count,
    {{ flag_to_bit('s.source_count > 1') }} as is_multi_source_story,
    e.source_key,
    e.source_id,
    e.source_name,
    e.category_key,
    e.category_name,
    e.author_key,
    e.author_name,
    e.timestamp_validity,
    e.syndication_indicator,
    e.publication_timestamp,
    e.has_publication_time,
    e.publication_date,
    e.publication_hour,
    e.publication_day_name,
    e.publication_iso_day_of_week,
    e.publication_is_weekend,
    e.publication_day_period,
    e.ingestion_timestamp,
    e.ingestion_date,
    e.article_updated_at
from {{ ref('int_articles_enriched') }} e
left join {{ ref('dim_stories') }} s on s.story_key = e.story_key
